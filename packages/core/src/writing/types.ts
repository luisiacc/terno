/** Plan 133: how someone writes, worked out on this machine. Everything in this folder is pure. */

export type VoiceScope = "you" | "account" | "domain" | "person";

/** "" when the text is too short or mixed to tell. */
export type WritingLanguage = "en" | "es" | "";

/** A sent message as the store has it: the body still holds quotes and the signature. */
export interface SentMail {
  id: string | number;
  /** lowercased addresses */
  to: readonly string[];
  cc: readonly string[];
  /** ms since the epoch */
  at: number;
  body: string;
  isReply: boolean;
  /** list mail, mass sends: never in a sample */
  bulk?: boolean;
  /** generated by this feature and sent unchanged: never in a sample, or the voice slowly becomes the model's (§8) */
  fromModel?: boolean;
}

/** The same message reduced to what the user wrote. */
export interface WrittenMail {
  id: string | number;
  to: readonly string[];
  cc: readonly string[];
  at: number;
  isReply: boolean;
  bulk: boolean;
  fromModel: boolean;
  text: string;
  words: number;
  /** names normalized, as typed otherwise: `hey {name},` */
  greeting: string | null;
  /** `Best,\n{me}`, `-{me}`, `thanks` */
  signOff: string | null;
  language: WritingLanguage;
}

export interface Share {
  text: string;
  /** 0 to 1, of all messages */
  share: number;
}

/** Local and deterministic, counted on everything before any de-duplication (§2). */
export interface Habits {
  messages: number;
  words: { median: number; p80: number };
  /** median words in a sentence, over messages long enough to have sentences */
  sentenceWords: number;
  greetings: Share[];
  noGreeting: number;
  signOffs: Share[];
  noSignOff: number;
  /** shares of messages */
  exclamation: number;
  emoji: number;
  bullets: number;
  /** starts its sentences in lowercase */
  lowercase: number;
  languages: Share[];
  replies: number;
  oneToOne: number;
}

export const VOICE_SITUATIONS = ["decline", "apologize", "acknowledge", "request", "negotiate", "schedule", "group"] as const;
export type VoiceSituation = (typeof VOICE_SITUATIONS)[number];

/** What the model adds to the counts (§3). Closed scales, so levels compare and render locally. */
export interface VoiceJudgment {
  traits: {
    formality: number;
    warmth: number;
    directness: number;
    detail: number;
    humor: number;
  };
  situations: Partial<Record<VoiceSituation, { formality?: number; length?: "shorter" | "same" | "longer"; note?: string }>>;
  /** manner only: at most 4, at most 14 words each */
  notes: string[];
}

export interface VoiceProfile {
  scope: VoiceScope;
  /** `you`, `account:3`, `domain:3:acme.com`, `person:3:tom@acme.com` */
  key: string;
  language: string;
  samples: number;
  habits: Habits;
  phrases: string[];
  judgment: VoiceJudgment | null;
  /** a person's profile learned on another account: it's absolute, so it carries over, whole and labelled (§1) */
  fromOtherAccount?: boolean;
}

/** The fewest messages a scope needs (§1). */
export const MIN_SAMPLES: Readonly<Record<VoiceScope, number>> = { you: 20, account: 15, domain: 8, person: 5 };

/** The caller's token estimate. Chars over four is good enough with §6.3's margin on top. */
export const estimateTokens = (text: string): number => Math.ceil(text.length / 4);
