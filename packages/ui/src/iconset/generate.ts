import { ALIASES, ICONS } from "./catalog";

/**
 * Plan 92: one module per icon, so the bundler puts each in the chunk that uses it (a composer-only icon stays in the
 * lazy composer); one module holding every factory would ride the entry chunk whole. Checked in; a test fails on drift.
 */
export const HEADER = "// Generated by `pnpm --filter @terno/ui gen:icons` from src/iconset/catalog.ts: edit that, not this.\n";

/** src/iconset/generated/<Name>.ts */
export function generateIcon(name: keyof typeof ICONS): string {
  const data = ICONS[name];
  return `${HEADER}import ${data} from "@hugeicons/core-free-icons/${data}";
import { icon } from "../render";

export const ${name} = /* @__PURE__ */ icon(${data}, "${name}");
`;
}

/** src/icons.ts: `@terno/ui/icons` */
export function generateIndex(): string {
  const names = Object.keys(ICONS).sort();
  const aliases = Object.entries(ALIASES).map(([alias, of]) => `export { ${of} as ${alias} } from "./iconset/generated/${of}";\n`);
  return `${HEADER}export type { Icon, IconProps } from "./iconset/render";
${names.map((n) => `export { ${n} } from "./iconset/generated/${n}";\n`).join("")}${aliases.join("")}`;
}
