/** Families with a domain per country: hotmail.co.uk, yahoo.com.mx, live.fr, yandex.ru, … (the label before the public suffix). */
const FAMILIES = new Set(["hotmail", "live", "outlook", "windowslive", "yahoo", "yandex", "gmx", "aol", "rediffmail", "libero"]);

export function isFreemail(registrable: string): boolean {
  if (EXACT.has(registrable)) return true;
  return FAMILIES.has(registrable.split(".")[0]!);
}
