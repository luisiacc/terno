// Plan 293 (CASA 6.2.1): the agents' command, Resources/bin/terno-mcp, is native/terno-mcp.c: a stdio-to-socket
// bridge to the MCP server inside the running app, with no Node and no Electron. This builds it: the offline
// manifest (the server's own initialize result and tools, written by build.mjs to dist/native/mcp-offline.json)
// becomes a header, and the C compiles for each platform the packagers ship.
import { execFileSync, spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const BRIDGE_SOURCE = join(root, "native/terno-mcp.c");
/** what macOS Electron 45 runs on, and so the bridge */
const MACOS_MIN = "12.0";

/** A JSON text as a C string literal (ASCII only: anything else is already a \u escape). */
function cString(json) {
  const ascii = json.replace(/[\u007f-￿]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`);
  return `"${ascii.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

/** The header the C includes: what the bridge answers while Terno can't be reached. */
export function bridgeHeader(manifest) {
  const { initialize, tools, latestVersion, supportedVersions, notRunning, lost, rejected } = manifest;
  // the initialize result's members after "protocolVersion", which the bridge negotiates
  const rest = JSON.stringify(initialize).slice(1, -1);
  return [
    "/* Generated by apps/desktop/scripts/mcp-bridge.mjs from the MCP server (packages/mcp/src/offline.ts). Don't edit. */",
    `#define LATEST_VERSION ${cString(JSON.stringify(latestVersion))}`,
    `static const char *const SUPPORTED_VERSIONS[] = {${supportedVersions.map((v) => cString(JSON.stringify(v))).join(", ")}};`,
    `static const char INITIALIZE_REST[] = ${cString(rest)};`,
    `static const char TOOLS_LIST_JSON[] = ${cString(JSON.stringify({ tools }))};`,
    `#define NOT_RUNNING_JSON ${cString(JSON.stringify(notRunning))}`,
    `#define LOST_JSON ${cString(JSON.stringify(lost))}`,
    `#define REJECTED_JSON ${cString(JSON.stringify(rejected))}`,
    "",
  ].join("\n");
}

/** The compiler and flags for a target (`os`: darwin or linux, `arch`: Node's name). */
export function bridgeCompiler({ os, arch }) {
  const warnings = ["-std=c11", "-O2", "-Wall", "-Wextra", "-Werror"];
  if (os === "darwin") {
    if (arch !== "arm64") throw new Error(`the bridge is built for macOS arm64 only, not ${arch}`);
    return { cc: "cc", flags: [...warnings, "-arch", "arm64", `-mmacosx-version-min=${MACOS_MIN}`] };
  }
  if (os === "linux") {
    const cross = { x64: "x86_64-linux-gnu-gcc", arm64: "aarch64-linux-gnu-gcc" }[arch];
    if (!cross) throw new Error(`no compiler for Linux ${arch}`);
    // TERNO_CC_X64 / TERNO_CC_ARM64 name another; the host's own gcc builds its own architecture. Static: a binary
    // linked against the build machine's glibc (2.34+ names __libc_start_main@GLIBC_2.34) wouldn't start on the older
    // systems Electron runs on, and a static one needs no glibc at all
    return { cc: process.env[`TERNO_CC_${arch.toUpperCase()}`] || (process.arch === arch ? "gcc" : cross), flags: [...warnings, "-static"] };
  }
  throw new Error(`no bridge for ${os}`);
}

/** Writes the header from `manifest` and compiles the bridge to `out` for `target`; returns `out`. */
export function buildBridge({ manifest, target, out, compiler = bridgeCompiler(target) }) {
  // the header goes beside nothing that ships
  const work = mkdtempSync(join(tmpdir(), "terno-bridge-"));
  try {
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(join(work, "mcp-offline.h"), bridgeHeader(manifest));
    execFileSync(compiler.cc, [...compiler.flags, "-I", work, "-o", out, BRIDGE_SOURCE], { stdio: "inherit" });
    if (target.os === "darwin") execFileSync("strip", ["-x", out]);
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
  return out;
}

/** The manifest build.mjs wrote beside the bundles. */
export function readManifest(dist) {
  return JSON.parse(readFileSync(join(dist, "native/mcp-offline.json"), "utf8"));
}

/** Where the packagers put each platform's bridge, read by extraResources as `${os}-${arch}`. */
export const bridgeDir = (stage, os, arch) => join(stage, "bridge", `${os === "darwin" ? "mac" : os}-${arch}`);

/** Where an .app keeps the bridge: the path Settings → Agents has always handed out. */
export const macBridgePath = (app) => join(app, "Contents/Resources/bin/terno-mcp");

/**
 * Throws unless the .app's bridge is a thin arm64 executable that verifies on its own, signed by the app's team and,
 * on a Developer ID build (`hardened`), with the hardened runtime and a secure timestamp, which notarization needs.
 */
export function assertMacBridge(app, { signed, hardened }) {
  const bridge = macBridgePath(app);
  const kind = execFileSync("file", ["-b", bridge], { encoding: "utf8" }).trim();
  if (!/^Mach-O 64-bit executable arm64$/.test(kind)) throw new Error(`${bridge} isn't a thin arm64 executable: ${kind}`);
  const verify = spawnSync("codesign", ["--verify", "--strict", "--verbose=2", bridge], { encoding: "utf8" });
  if (verify.status !== 0) throw new Error(`${bridge} doesn't verify: ${verify.stderr.trim()}`);
  if (!signed) return console.log(`✓ ${bridge}: arm64, verifies (ad-hoc)`);
  const details = (path) => spawnSync("codesign", ["-dv", "--verbose=2", path], { encoding: "utf8" }).stderr;
  const team = (text) => /^TeamIdentifier=(.+)$/m.exec(text)?.[1];
  const own = details(bridge);
  if (!team(own) || team(own) === "not set" || team(own) !== team(details(app))) throw new Error(`${bridge} isn't signed by the app's team (${team(own)})`);
  if (hardened) {
    if (!/flags=0x[0-9a-f]*\(runtime\)/.test(own)) throw new Error(`${bridge} isn't signed with the hardened runtime`);
    if (!/^Timestamp=/m.test(own)) throw new Error(`${bridge} has no secure timestamp`);
  }
  console.log(`✓ ${bridge}: arm64, signed by ${team(own)}${hardened ? ", hardened runtime, timestamped" : ""}`);
}

/** The newest `GLIBC_x.y` a binary names (its version needs are in .dynstr), as [x, y]; null when it names none. */
export function newestGlibc(bytes) {
  let newest = null;
  for (const m of bytes.toString("latin1").matchAll(/GLIBC_(\d+)\.(\d+)/g)) {
    const v = [Number(m[1]), Number(m[2])];
    if (!newest || v[0] > newest[0] || (v[0] === newest[0] && v[1] > newest[1])) newest = v;
  }
  return newest;
}

/** `file`'s words for each Linux architecture */
const ELF_ARCH = { x64: "x86-64", arm64: "ARM aarch64" };

/**
 * Throws unless a Linux package's bridge is a statically linked executable ELF for `arch`, so it runs wherever Terno
 * does whatever glibc the system has; a dynamic one must need no newer glibc than Electron's own binary (`electron`).
 */
export function assertLinuxBridge(bridge, { arch, electron }) {
  const kind = execFileSync("file", ["-b", bridge], { encoding: "utf8" }).trim();
  if (!kind.startsWith("ELF 64-bit") || !kind.includes(ELF_ARCH[arch])) throw new Error(`${bridge} isn't an ${ELF_ARCH[arch]} executable: ${kind}`);
  if (!(statSync(bridge).mode & 0o111)) throw new Error(`${bridge} isn't executable`);
  if (kind.includes("statically linked")) {
    console.log(`✓ ${bridge}: ${ELF_ARCH[arch]}, executable, statically linked`);
    return;
  }
  const own = newestGlibc(readFileSync(bridge));
  const theirs = newestGlibc(readFileSync(electron));
  if (own && theirs && (own[0] > theirs[0] || (own[0] === theirs[0] && own[1] > theirs[1]))) throw new Error(`${bridge} needs glibc ${own.join(".")}, newer than Electron's ${theirs.join(".")}`);
  console.log(`✓ ${bridge}: ${ELF_ARCH[arch]}, executable, glibc ${own?.join(".") ?? "none"} (Electron ${theirs?.join(".") ?? "none"})`);
}
